#!/usr/bin/env python3
"""Turn ASCII art into a C source file holding a 2-bitplane Intuition Image's plane data.

Usage: mkimage.py ART.txt NAME OUT.c
ART.txt: equal-length rows; lines starting with '#' and blank lines are ignored.
Pixel key: . W K O = the 1.3 Workbench pens blue/white/black/orange (0-3).

Emits two plane sets, because the Workbench palette changed in 2.0:
  NAME_13 for 1.x  (. W K O -> pens 0 1 2 3: blue, white, black, orange)
  NAME_20 for 2.0+ (. W K O -> pens 0 2 1 3: grey, white, black, blue)
plus NAME_W, NAME_H and NAME_WORDS (UWORDs per set).
"""
import sys

MAP_13 = {".": 0, "W": 1, "K": 2, "O": 3}
MAP_20 = {".": 0, "W": 2, "K": 1, "O": 3}


def load_art(path):
    rows = [line.rstrip("\r\n") for line in open(path)]
    rows = [r for r in rows if r and not r.startswith("#")]
    assert rows and all(len(r) == len(rows[0]) for r in rows), "ragged art"
    return rows


def planes(art, pens):
    w = len(art[0])
    words = (w + 15) // 16
    out = []
    for p in range(2):
        for row in art:
            for wd in range(words):
                bits = 0
                for x in range(wd * 16, wd * 16 + 16):
                    pen = pens[row[x]] if x < w else 0
                    bits = (bits << 1) | ((pen >> p) & 1)
                out.append(bits)
    return out


def carray(name, data):
    lines = []
    for i in range(0, len(data), 12):
        lines.append("    " + ", ".join(f"0x{v:04X}" for v in data[i:i + 12]) + ",")
    return f"const UWORD {name}[] = {{\n" + "\n".join(lines) + "\n};\n"


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    art, name, out = load_art(sys.argv[1]), sys.argv[2], sys.argv[3]
    p13, p20 = planes(art, MAP_13), planes(art, MAP_20)
    with open(out, "w", newline="\n") as f:
        f.write(f"/* Generated by tools/mkimage.py from {sys.argv[1]}; do not edit. */\n")
        f.write("#include <exec/types.h>\n\n")
        f.write(f"const UWORD {name}_W = {len(art[0])}, {name}_H = {len(art)}, {name}_WORDS = {len(p13)};\n\n")
        f.write(carray(name + "_13", p13) + "\n" + carray(name + "_20", p20))


if __name__ == "__main__":
    main()
